#!/usr/bin/env python3
"""Generate compositions/hud.html — the full-length HUD overlay — for a variant project.

Reads variant.json (style/aspect/palette), STORYBOARD.md (frame spans + `- hud_label:`) and
audiomap.json (duration, strong kicks, first downbeat). Draws: brand box (TL), odometer
timecode + beat pip (TR), series chip under the brand box (per frame with hud_label), and a
bottom band with a progress ruler + ticker. Everything is transform/0ms-set based → seek-safe.

  python3 make_hud.py videos/<name>
"""
import json, math, sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from gr_common import aspect_cfg, load_style, parse_storyboard  # noqa: E402

FONT_FACE = """        @font-face { font-family: "Paperlogy"; src: url("assets/fonts/Paperlogy-8ExtraBold.ttf") format("truetype"); font-weight: 800; font-display: block; }
        @font-face { font-family: "Paperlogy"; src: url("assets/fonts/Paperlogy-5Medium.ttf") format("truetype"); font-weight: 500; font-display: block; }
        @font-face { font-family: "Paperlogy"; src: url("assets/fonts/Paperlogy-4Regular.ttf") format("truetype"); font-weight: 400; font-display: block; }"""


def main():
    proj = Path(sys.argv[1]).resolve()
    spec = json.loads((proj / "variant.json").read_text())
    style, _ = load_style(spec.get("style", "bold-beat"))
    tok = dict(style["tokens"]); tok.update(spec.get("palette", {}))
    box, text, acc = tok[style["hud"]["box"]], tok[style["hud"]["text"]], tok[style["hud"]["accent"]]
    A = aspect_cfg(spec.get("aspect", "16:9")); W, H, L = A["w"], A["h"], A["hud"]
    am = json.loads((proj / "audiomap.json").read_text())
    D = am["audio"]["duration_sec"]
    downs = am["grid"].get("downbeats_sec") or [0.9]
    boot = round(next((d for d in downs if d > 0.3), 0.9), 3)
    kicks = [round(e["t"], 3) for e in am["events"] if e["drum"] in ("kick", "snare") and e["energy"] > 0.1 and e["t"] > boot]
    chips = []
    for f in parse_storyboard(proj / "STORYBOARD.md"):
        lab = f["fields"].get("hud_label")
        if lab and "span" in f:
            k, _, n = lab.partition("·")
            chips.append((f["span"][0], f["span"][1], k.strip(), n.strip()))
    year = spec.get("hud_year", 2026)
    ticker = spec.get("hud_ticker", "IT ✦ AI ✦ 자격증 ✦ 교양 ✦ GOLDEN RABBIT BOOKS ✦ goldenrabbit.co.kr ✦ ")
    dg = L["tc_px"] + 5  # digit cell height
    ruler_w = W - 2 * L["edge"]
    n_ticks = int(ruler_w // 40) + 1

    def strip(n, extra0=True):
        return "".join(f'<span class="hud-dg">{x}</span>' for x in [str(i) for i in range(n)] + (["0"] if extra0 else []))

    ticks = "".join(f'<span class="hud-tick{" hud-tick--major" if i % 5 == 0 else ""}" style="transform: translateX({i*40}px)"></span>' for i in range(n_ticks))
    chip_html = "".join(f'<div class="hud-ser" id="hud_ser{i}"><span class="hud-ser-k">{k}</span><span class="hud-ser-n">{n}</span></div>' for i, (_, _, k, n) in enumerate(chips))
    reps = max(6, math.ceil(3 * W / (len(ticker) * L["ticker_px"] * 0.55)))

    html = f'''<!doctype html>
<html lang="ko">
  <head>
    <meta charset="UTF-8" />
    <!-- Generated by .claude/skills/goldenrabbit-promo/scripts/make_hud.py — re-run instead of hand-editing. -->
  </head>
  <body>
    <template>
      <style>
{FONT_FACE}
        #stage {{ position: absolute; inset: 0; width: {W}px; height: {H}px; overflow: hidden; pointer-events: none; background: transparent; }}
        .hud-box {{ position: absolute; top: {L["box_top"]}px; height: {L["box_h"]}px; display: flex; align-items: center; gap: 12px; padding: 0 14px; background: {box}; transform-origin: 0% 50%; }}
        #hud_brand {{ left: {L["edge"]}px; }}
        .hud-brand-w {{ font-family: "Archivo Black", sans-serif; font-size: {L["brand_px"]}px; letter-spacing: 0.14em; color: {text}; }}
        .hud-brand-s {{ font-family: "IBM Plex Mono", monospace; font-weight: 700; font-size: {L["brand_px"]-3}px; letter-spacing: 0.12em; color: {acc}; }}
        #hud_tcbox {{ right: {L["edge"]}px; transform-origin: 100% 50%; }}
        .hud-tc {{ display: flex; align-items: center; font-family: "IBM Plex Mono", monospace; font-weight: 700; font-size: {L["tc_px"]}px; color: {acc}; }}
        .hud-dig {{ display: inline-block; height: {dg}px; overflow: hidden; }}
        .hud-strip {{ display: block; }}
        .hud-dg {{ display: block; height: {dg}px; line-height: {dg}px; text-align: center; width: {round(L["tc_px"]*0.63)}px; }}
        .hud-colon {{ display: inline-block; width: {round(L["tc_px"]*0.63)}px; text-align: center; opacity: 0.55; }}
        #hud_pip {{ width: 12px; height: 12px; background: {acc}; opacity: 0.18; }}
        #hud_serwrap {{ position: absolute; left: {L["edge"]}px; top: {L["chip_top"]}px; height: {L["box_h"]-6}px; }}
        .hud-ser {{ position: absolute; left: 0; top: 0; height: {L["box_h"]-6}px; display: flex; align-items: center; gap: 10px; padding: 0 12px; background: {box}; white-space: nowrap; transform-origin: 0% 50%; opacity: 0; }}
        .hud-ser-k {{ font-family: "IBM Plex Mono", monospace; font-weight: 700; font-size: {L["brand_px"]-3}px; letter-spacing: 0.12em; color: {text}; }}
        .hud-ser-n {{ font-family: "Paperlogy", sans-serif; font-weight: 800; font-size: {L["brand_px"]+1}px; color: {acc}; }}
        #hud_band {{ position: absolute; left: 0; top: {L["band_top"]}px; width: {W}px; height: {L["band_h"]}px; background: {box}; overflow: hidden; }}
        #hud_ruler {{ position: absolute; left: {L["edge"]}px; top: 6px; width: {ruler_w}px; height: 18px; }}
        .hud-tick {{ position: absolute; left: 0; bottom: 0; width: 2px; height: 7px; background: rgba(255,255,255,0.28); }}
        .hud-tick--major {{ height: 13px; background: {text}; }}
        #hud_rail {{ position: absolute; left: 0; bottom: 0; width: {ruler_w}px; height: 2px; background: rgba(255,255,255,0.14); }}
        #hud_prog {{ position: absolute; left: 0; bottom: 0; width: {ruler_w}px; height: 2px; background: {acc}; transform-origin: 0% 50%; }}
        #hud_markx {{ position: absolute; left: 0; top: 0; width: 0; height: 0; }}
        #hud_mark {{ position: absolute; left: -7px; top: -4px; width: 0; height: 0; border-left: 7px solid transparent; border-right: 7px solid transparent; border-top: 10px solid {acc}; }}
        #hud_tickerwrap {{ position: absolute; left: 0; top: 30px; width: {W}px; height: {L["band_h"]-34}px; overflow: hidden; }}
        #hud_ticker {{ position: absolute; left: 0; top: 0; height: {L["band_h"]-34}px; line-height: {L["band_h"]-34}px; white-space: nowrap; font-family: "Paperlogy", sans-serif; font-weight: 800; font-size: {L["ticker_px"]}px; letter-spacing: 0.04em; color: {acc}; }}
      </style>

      <div id="stage" data-composition-id="hud" data-width="{W}" data-height="{H}" data-duration="{D}">
        <div class="hud-box" id="hud_brand"><span class="hud-brand-w">GOLDEN RABBIT</span><span class="hud-brand-s">✦ BOOKS {year}</span></div>
        <div id="hud_serwrap">{chip_html}</div>
        <div class="hud-box" id="hud_tcbox">
          <span id="hud_pip"></span>
          <span class="hud-tc">
            <span class="hud-dg" style="display:inline-block">0</span><span class="hud-dg" style="display:inline-block">0</span><span class="hud-colon">:</span>
            <span class="hud-dig" data-layout-allow-overflow="" data-layout-ignore=""><span class="hud-strip" id="hud_s10">{strip(6, False)}</span></span><span class="hud-dig" data-layout-allow-overflow="" data-layout-ignore=""><span class="hud-strip" id="hud_s1">{strip(10)}</span></span><span class="hud-colon">:</span>
            <span class="hud-dig" data-layout-allow-overflow="" data-layout-ignore=""><span class="hud-strip" id="hud_f10">{strip(3)}</span></span><span class="hud-dig" data-layout-allow-overflow="" data-layout-ignore=""><span class="hud-strip" id="hud_f1">{strip(10)}</span></span>
          </span>
        </div>
        <div id="hud_band">
          <div id="hud_ruler">{ticks}<div id="hud_rail"></div><div id="hud_prog"></div><div id="hud_markx"><div id="hud_mark"></div></div></div>
          <div id="hud_tickerwrap"><div id="hud_ticker" data-layout-allow-overflow="">{ticker * reps}</div></div>
        </div>
      </div>

      <script>
        (function () {{
          var D = {D}, H = {dg}, BOOT = {boot}, RW = {ruler_w}, BAND = {L["band_h"]};
          var KICKS = {json.dumps(kicks)};
          var CHIPS = {json.dumps([[a, b] for a, b, _, _ in chips])};
          var tl = gsap.timeline({{ paused: true }});
          tl.set(["#hud_brand", "#hud_tcbox"], {{ scaleX: 0 }}, 0);
          tl.set("#hud_band", {{ y: BAND }}, 0);
          tl.to("#hud_band", {{ y: 0, duration: 0.32, ease: "expo.out" }}, BOOT);
          tl.to("#hud_brand", {{ scaleX: 1, duration: 0.18, ease: "power3.out" }}, BOOT + 0.06);
          tl.to("#hud_tcbox", {{ scaleX: 1, duration: 0.18, ease: "power3.out" }}, BOOT + 0.12);
          tl.fromTo("#hud_prog", {{ scaleX: 0 }}, {{ scaleX: 1, duration: D, ease: "none" }}, 0);
          tl.fromTo("#hud_markx", {{ x: 0 }}, {{ x: RW, duration: D, ease: "none" }}, 0);
          tl.fromTo("#hud_ticker", {{ x: 0 }}, {{ x: -{round(1.35 * W)}, duration: D, ease: "none" }}, 0);
          tl.to("#hud_f1", {{ y: -10 * H, duration: 1 / 3, ease: "steps(10)", repeat: {math.ceil(D * 3)} }}, 0);
          for (var k = 0; k / 3 < D; k++) tl.set("#hud_f10", {{ y: -(k % 3) * H }}, k / 3);
          for (var s = 0; s < D; s++) {{
            tl.set("#hud_s1", {{ y: -(s % 10) * H }}, s);
            if (s % 10 === 0) tl.set("#hud_s10", {{ y: -(s / 10) * H }}, s);
          }}
          KICKS.forEach(function (t) {{ tl.set("#hud_pip", {{ opacity: 1 }}, t); tl.set("#hud_pip", {{ opacity: 0.18 }}, t + 0.12); }});
          CHIPS.forEach(function (c, i) {{
            var id = "#hud_ser" + i;
            tl.set(id, {{ opacity: 1, scaleX: 0 }}, c[0]);
            tl.to(id, {{ scaleX: 1, duration: 0.14, ease: "power3.out" }}, c[0]);
            tl.set(id, {{ opacity: 0 }}, c[1]);
          }});
          tl.seek(0);
          window.__timelines = window.__timelines || {{}};
          window.__timelines["hud"] = tl;
        }})();
      </script>
    </template>
  </body>
</html>
'''
    out = proj / "compositions" / "hud.html"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(html)
    print(f"✓ {out} · {W}×{H} · {len(chips)} series chips · {len(kicks)} beat pips · boot {boot}s")


if __name__ == "__main__":
    main()
