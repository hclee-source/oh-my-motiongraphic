#!/usr/bin/env python3
"""v3: generate compositions/footage.html (track 1) from .work/edl.json — every non-insert second of the song is footage.

Each shot = one muted <video class="clip"> (scene-local timing, data-media-start, data-playback-rate) inside two NON-timed
wrappers: #ft_w<id> (scale push about the shot's origin) and #ft_m<id> (static mirror). Dissolves overlap the incoming
shot by `dis` and fade its opacity in; `pre` starts a shot early (opaque) under an insert's exit dissolve.
Re-run after editing edl.json; never hand-edit the output.
"""
import json
from pathlib import Path

PROJ = Path(__file__).resolve().parent.parent
edl = json.loads((PROJ / ".work" / "edl.json").read_text())
DUR = json.loads((PROJ / "audiomap.json").read_text())["audio"]["duration_sec"]
W, H = 1920, 1080

html, js = [], []
for i, sh in enumerate(edl["shots"]):
    sid = sh["id"]
    a, b = sh["t"]
    lead = sh.get("dis", 0.0) + sh.get("pre", 0.0)
    start = round(a - lead, 3)
    dur = round(b - start, 3)
    rate = sh.get("r", 1.0)
    mstart = round(sh["m"] - lead * rate, 3)
    assert mstart >= -1e-6, f"{sid}: media start < 0"
    ox, oy = sh.get("o", [W / 2, H / 2])
    mir = ' style="transform: scaleX(-1)"' if sh.get("mir") else ""
    rate_attr = f' data-playback-rate="{rate}"' if rate != 1.0 else ""
    html.append(
        f'<div id="ft_w{sid}" class="ft-w" style="transform-origin:{ox}px {oy}px" data-layout-ignore>'
        f'<div id="ft_m{sid}" class="ft-m"{mir}>'
        f'<video id="ft_v{sid}" class="clip ft-v" src="assets/footage/{sh["c"]}.mp4" muted playsinline '
        f'data-start="{start}" data-duration="{dur}" data-media-start="{max(0.0, mstart)}"{rate_attr} data-track-index="{i % 2}"></video>'
        f'</div></div>')
    s0, s1 = sh.get("s", [1.0, 1.0])
    js.append(f'tl.fromTo("#ft_w{sid}",{{scale:{s0}}},{{scale:{s1},duration:{dur},ease:"none",immediateRender:false}},{start});')
    if sh.get("dis"):
        js.append(f'tl.fromTo("#ft_v{sid}",{{opacity:0}},{{opacity:1,duration:{sh["dis"]},ease:"sine.inOut",immediateRender:false}},{start});')
    if sh.get("fadein"):
        f0, f1 = sh["fadein"]
        js.append(f'tl.fromTo("#ft_v{sid}",{{opacity:0}},{{opacity:1,duration:{round(f1 - f0, 3)},ease:"sine.out",immediateRender:false}},{f0});')
    if sh.get("blur"):
        b0, b1 = sh["blur"]
        js.append(f'tl.fromTo("#ft_w{sid}",{{filter:"blur({b0}px)"}},{{filter:"blur({b1}px)",duration:{dur},ease:"sine.out",immediateRender:false}},{start});')
    if sh.get("dim"):
        d0, d1 = sh["dim"]
        js.append(f'tl.fromTo("#ft_dim",{{opacity:{d0}}},{{opacity:{d1},duration:{round(b - a, 3)},ease:"sine.inOut",immediateRender:false}},{a});')
        js.append(f'tl.set("#ft_dim",{{opacity:0}},{b});')

# initial hidden states for fade-in shots live in markup (first shot starts at 0)
first_fade = [sh for sh in edl["shots"] if sh.get("fadein")]
init_css = "".join(f'#ft_v{sh["id"]} {{ opacity: 0; }}\n        ' for sh in first_fade)
bo_t, bo_d = edl.get("black_out", [DUR, 0])
js.append(f'tl.fromTo("#ft_black",{{opacity:0}},{{opacity:1,duration:{bo_d},ease:"sine.in",immediateRender:false}},{bo_t});')
js.append(f'tl.set({{}},{{}},{DUR});')

out = f"""<!doctype html>
<html lang="ko">
  <head><meta charset="UTF-8" /><!-- Generated by .work/make_footage.py from .work/edl.json — re-run, don't hand-edit. --></head>
  <body>
    <template>
      <style>
        #stage {{ position: absolute; inset: 0; width: {W}px; height: {H}px; overflow: hidden; background: #000; }}
        .ft-w, .ft-m {{ position: absolute; left: 0; top: 0; width: {W}px; height: {H}px; }}
        .ft-v {{ position: absolute; left: 0; top: 0; width: {W}px; height: {H}px; object-fit: cover; }}
        #ft_dim {{ position: absolute; inset: 0; background: #02030A; opacity: 0; pointer-events: none; }}
        #ft_black {{ position: absolute; inset: 0; background: #000; opacity: 0; pointer-events: none; }}
        {init_css}
      </style>
      <div id="stage" data-composition-id="footage" data-width="{W}" data-height="{H}" data-duration="{DUR}" data-layout-ignore="">
        {chr(10).join('        ' + h for h in html).lstrip()}
        <div id="ft_dim" data-layout-ignore></div>
        <div id="ft_black" data-layout-ignore></div>
      </div>
      <script>
        (function () {{
          var tl = gsap.timeline({{ paused: true }});
          {chr(10).join('          ' + l for l in js).lstrip()}
          tl.seek(0);
          window.__timelines = window.__timelines || {{}};
          window.__timelines["footage"] = tl;
        }})();
      </script>
    </template>
  </body>
</html>
"""
(PROJ / "compositions" / "footage.html").write_text(out)
print(f"footage.html: {len(edl['shots'])} shots, {len(js)} timeline lines")
